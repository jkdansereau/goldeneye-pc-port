#!/usr/bin/env python3
"""Generate port/convert/convert_data.c: the decomp metadata the C asset
converter (port/convert/) needs, as constants, so it runs with no scripts/ or
assets/ tree and no Python.

Embedded (dev-time only; the output is committed):
  * scripts/filelist.{u,e,j}.csv rows  -> {rom offset, size, basename}
    (basename = last path component, ".bin" stripped; same keying the Python
     emit scripts use, duplicates resolved last-wins by the C lookup)
  * assets/obseg/file_resource_table.inc.c names, in table order
  * MODELFILEHEADER(name, ..., NS, ..., NT) values from every
    assets/**/modelFileHeader.inc.c

Usage: python tools_pc/gen_convert_data.py [--check]   (from the repo root)
  --check  write nothing; exit 1 if the committed file is out of date (CI).
"""
import csv, os, re, sys

OUT = "port/convert/convert_data.c"
REGIONS = (("ntsc-final", "u"), ("pal-final", "e"), ("jpn-final", "j"))


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def filelist(letter):
    rows = []
    for r in csv.reader(open("scripts/filelist.%s.csv" % letter)):
        if len(r) < 3 or not r[2]:
            continue
        base = r[2].rsplit("/", 1)[-1]
        if base.endswith(".bin"):
            base = base[:-4]
        rows.append((int(r[0]), int(r[1]), base))
    return rows


def table_names():
    out = []
    for line in open("assets/obseg/file_resource_table.inc.c"):
        m = re.search(r'\{\s*\w+\s*,\s*"([^"]+)"', line)
        if m:
            out.append(m.group(1))
    return out


def nsnt():
    d = {}
    for root, dirs, files in os.walk("assets"):
        dirs.sort()          # fixed walk order: duplicate names resolve the
        for fn in sorted(files):   # same way on every OS (last one wins)
            if fn.lower().endswith("modelfileheader.inc.c"):
                for line in open(os.path.join(root, fn)):
                    m = re.search(r"MODELFILEHEADER\((.*)\)\s*;?\s*$", line)
                    if not m:
                        continue
                    a = [x.strip() for x in m.group(1).split(",")]
                    if len(a) < 9:
                        continue
                    try:
                        d[a[0]] = (int(a[4], 0), int(a[8], 0))
                    except ValueError:
                        pass
    return d


def main():
    if not os.path.isdir("assets") or not os.path.isdir("scripts"):
        sys.exit("run from the repo root")
    w = []
    w.append("/* GENERATED by tools_pc/gen_convert_data.py -- do not edit. */")
    w.append('#include "convert.h"')
    w.append("")
    for region, letter in REGIONS:
        rows = filelist(letter)
        sym = region.replace("-", "_")
        w.append("static const CvFileRow cv_files_%s[] = {" % sym)
        for off, size, base in rows:
            w.append("    {%du, %du, %s}," % (off, size, cstr(base)))
        w.append("};")
        w.append("")
    w.append("const CvRegionData cv_regions[CV_NREGIONS] = {")
    for region, letter in REGIONS:
        sym = region.replace("-", "_")
        w.append("    {%s, %s, cv_files_%s, sizeof(cv_files_%s) / sizeof(cv_files_%s[0])},"
                 % (cstr(region), cstr(letter), sym, sym, sym))
    w.append("};")
    w.append("")
    names = table_names()
    w.append("const char *const cv_table_names[] = {")
    for n in names:
        w.append("    %s," % cstr(n))
    w.append("};")
    w.append("const int cv_table_count = %d;" % len(names))
    w.append("")
    d = nsnt()
    w.append("const CvNsNt cv_nsnt[] = {")
    for k in sorted(d):
        w.append("    {%s, %d, %d}," % (cstr(k), d[k][0], d[k][1]))
    w.append("};")
    w.append("const int cv_nsnt_count = %d;" % len(d))
    text = "\n".join(w) + "\n"
    if "--check" in sys.argv[1:]:
        cur = open(OUT, newline="").read().replace("\r\n", "\n") if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("%s is out of date: run `python tools_pc/gen_convert_data.py` and commit it" % OUT)
        print("%s is current" % OUT)
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d table names, %d nsnt)" % (OUT, len(names), len(d)))


main()
